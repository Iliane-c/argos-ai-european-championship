#!/usr/bin/env bash
# One-command runner for the full Task 3 Hybrid v2 unlearning pipeline.
# Works on Google Colab, local GPU machines, and JURECA interactive GPU nodes.
#
# Quick start:
#   TASK_DIR=/path/to/task3 bash unlearning/run_pipeline.sh
#
# Key environment variables (all optional except TASK_DIR when files aren't in $PWD):
#   TASK_DIR            Directory containing model.pt and forget_images.npz (and optional task_template.py).
#   OUT_DIR             Output directory (default: $TASK_DIR/output/hybrid_v2).
#   POOL_PATH           Retain proxy image pool (.npy, .npz, or directory of images).
#                       Checks $TASK_DIR/coco224.npy and prior COCO pools before downloading COCO val2017.
#   AUTO_DOWNLOAD_COCO  1 (default) to download COCO val2017 (~778MB) if POOL_PATH is missing; 0 to fail instead.
#   USE_INDOMAIN        auto (default: 1 for full/fast, 0 for smoke) | 1 | 0 (SDXL-Turbo 45-class anchors).
#   INDOMAIN_PER_CLASS  Images per forget class generated by gen_indomain.py (default: 120 full, 60 fast).
#   MODE                full (default, competition quality) | fast (Colab T4 friendly) | smoke (tiny dry-run).
#   STAGES              all (default) or comma-separated subset of:
#                       diagnose,indomain,retain,shadow,oracle,wave1,wave2,soup
#   SKIP_SHADOW         1 (default: skip noisy from-scratch Shadow-Gold) | 0 (enable Shadow-Gold).
#   FORCE               0 (default, skip stages whose outputs exist so reruns resume) | 1 (overwrite all).
#   DEVICE              auto (default) | cuda | cpu.
#   AMP                 auto (default: bf16 on Ampere+, fp16 on T4/Volta, fp32 on CPU) | bf16 | fp16 | fp32.
#   PYTHON_BIN          Explicit Python interpreter (auto-detects venv / python3 otherwise).
#   AUTO_INSTALL_DEPS   0 (default) | 1 (pip install missing timm/numpy/pillow/diffusers automatically).

set -euo pipefail

if [[ "${1:-}" == "-h" || "${1:-}" == "--help" ]]; then
    sed -n '2,25p' "$0" | sed 's/^# \{0,1\}//'
    exit 0
fi

REPO_UNLEARNING_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

TASK_DIR="${TASK_DIR:-$PWD}"
OUT_DIR="${OUT_DIR:-$TASK_DIR/output/hybrid_v2}"
MODE="${MODE:-full}"
STAGES="${STAGES:-all}"
SKIP_SHADOW="${SKIP_SHADOW:-1}"
FORCE="${FORCE:-0}"
AUTO_DOWNLOAD_COCO="${AUTO_DOWNLOAD_COCO:-1}"
AUTO_INSTALL_DEPS="${AUTO_INSTALL_DEPS:-0}"
USE_INDOMAIN="${USE_INDOMAIN:-auto}"
INDOMAIN_PER_CLASS="${INDOMAIN_PER_CLASS:-}"
DEVICE="${DEVICE:-auto}"
AMP="${AMP:-auto}"

stage_enabled() {
    local name="$1"
    [[ "$STAGES" == "all" ]] && return 0
    [[ ",$STAGES," == *",$name,"* ]]
}

# ---------------------------------------------------------------------------
# 1. Resolve Python interpreter & verify dependencies
# ---------------------------------------------------------------------------
resolve_python() {
    if [[ -n "${PYTHON_BIN:-}" ]]; then
        echo "$PYTHON_BIN"
    elif [[ -n "${UNLEARNING_PYTHON:-}" ]]; then
        echo "$UNLEARNING_PYTHON"
    elif [[ -x "$TASK_DIR/.venv/bin/python" ]]; then
        echo "$TASK_DIR/.venv/bin/python"
    elif [[ -x "$REPO_UNLEARNING_DIR/.venv/bin/python" ]]; then
        echo "$REPO_UNLEARNING_DIR/.venv/bin/python"
    elif command -v python3 >/dev/null 2>&1; then
        command -v python3
    elif command -v python >/dev/null 2>&1; then
        command -v python
    else
        echo "ERROR: No Python interpreter found. Set PYTHON_BIN=/path/to/python." >&2
        exit 1
    fi
}

PY="$(resolve_python)"

check_deps() {
    local need_timm="1"
    if [[ -f "$TASK_DIR/task_template.py" ]] && ! grep -q "timm" "$TASK_DIR/task_template.py"; then
        need_timm="0"
    fi
    local missing
    missing="$("$PY" - "$need_timm" <<'PY'
import importlib, sys
reqs = [("torch", "torch"), ("numpy", "numpy"), ("PIL", "pillow")]
if sys.argv[1] == "1":
    reqs.append(("timm", "timm"))
bad = []
for mod, pkg in reqs:
    try:
        importlib.import_module(mod)
    except Exception:
        bad.append(pkg)
print(" ".join(bad))
PY
)"
    if [[ -n "$missing" ]]; then
        if [[ "$AUTO_INSTALL_DEPS" == "1" ]]; then
            echo "[setup] Installing missing Python packages: $missing"
            "$PY" -m pip install -q $missing
        else
            echo "ERROR: Missing Python packages: $missing" >&2
            echo "Install them with: $PY -m pip install $missing (or re-run with AUTO_INSTALL_DEPS=1)" >&2
            exit 1
        fi
    fi
}

check_deps

# ---------------------------------------------------------------------------
# 2. Validate task inputs & detect hardware / AMP precision
# ---------------------------------------------------------------------------
if [[ ! -f "$TASK_DIR/model.pt" || ! -f "$TASK_DIR/forget_images.npz" ]]; then
    echo "ERROR: TASK_DIR ($TASK_DIR) must contain model.pt and forget_images.npz." >&2
    echo "Example: TASK_DIR=/content/task3 bash unlearning/run_pipeline.sh" >&2
    exit 1
fi

if [[ "$DEVICE" == "auto" ]]; then
    DEVICE="$("$PY" -c "import torch; print('cuda' if torch.cuda.is_available() else 'cpu')")"
fi

NGPUS="${NGPUS:-auto}"
if [[ "$NGPUS" == "auto" ]]; then
    if [[ "$DEVICE" == cuda* ]]; then
        NGPUS="$("$PY" -c "import torch; print(max(1, torch.cuda.device_count()))")"
    else
        NGPUS="1"
    fi
fi

if [[ "$AMP" == "auto" ]]; then
    if [[ "$DEVICE" == cuda* ]]; then
        AMP="$("$PY" -c "import torch; print('bf16' if torch.cuda.is_bf16_supported() else 'fp16')")"
    else
        AMP="fp32"
    fi
fi

# ---------------------------------------------------------------------------
# 3. Mode hyperparameters (full | fast | smoke)
# ---------------------------------------------------------------------------
case "$MODE" in
    full)
        [[ "$USE_INDOMAIN" == "auto" ]] && USE_INDOMAIN="1"
        INDOMAIN_PER_CLASS="${INDOMAIN_PER_CLASS:-120}"
        DIAG_GRIDS="${SAVE_GRIDS:-20}"
        RETAIN_PER_CLASS="${PER_CLASS:-300}"
        RETAIN_MIN_PER_CLASS="${MIN_PER_CLASS:-15}"
        RETAIN_AUDIT="${AUDIT_COUNT:-600}"
        SHADOW_MODELS="${NUM_SHADOW_MODELS:-3}"
        SHADOW_EPOCHS="${SHADOW_EPOCHS:-12}"
        SHADOW_BS="${SHADOW_BS:-32}"
        EPOCHS_MAIN="${EPOCHS_MAIN:-8}"
        EPOCHS_BRANCH="${EPOCHS_BRANCH:-8}"
        KFOLD_FOLDS="${KFOLD_FOLDS:-5}"
        KFOLD_EPOCHS="${KFOLD_EPOCHS:-5}"
        TRAIN_BLOCKS_LAST6=6
        TRAIN_BLOCKS_LAST5=5
        TRAIN_BLOCKS_ALL=12
        ORACLE_WEIGHT_SAMPLES=4
        ;;
    fast)
        [[ "$USE_INDOMAIN" == "auto" ]] && USE_INDOMAIN="1"
        INDOMAIN_PER_CLASS="${INDOMAIN_PER_CLASS:-60}"
        DIAG_GRIDS="${SAVE_GRIDS:-8}"
        RETAIN_PER_CLASS="${PER_CLASS:-200}"
        RETAIN_MIN_PER_CLASS="${MIN_PER_CLASS:-10}"
        RETAIN_AUDIT="${AUDIT_COUNT:-500}"
        SHADOW_MODELS="${NUM_SHADOW_MODELS:-2}"
        SHADOW_EPOCHS="${SHADOW_EPOCHS:-6}"
        SHADOW_BS="${SHADOW_BS:-32}"
        EPOCHS_MAIN="${EPOCHS_MAIN:-6}"
        EPOCHS_BRANCH="${EPOCHS_BRANCH:-5}"
        KFOLD_FOLDS="${KFOLD_FOLDS:-3}"
        KFOLD_EPOCHS="${KFOLD_EPOCHS:-4}"
        TRAIN_BLOCKS_LAST6=6
        TRAIN_BLOCKS_LAST5=5
        TRAIN_BLOCKS_ALL=12
        ORACLE_WEIGHT_SAMPLES=2
        ;;
    smoke)
        [[ "$USE_INDOMAIN" == "auto" ]] && USE_INDOMAIN="0"
        INDOMAIN_PER_CLASS="${INDOMAIN_PER_CLASS:-0}"
        DIAG_GRIDS=0
        RETAIN_PER_CLASS=4
        RETAIN_MIN_PER_CLASS=1
        RETAIN_AUDIT=4
        SHADOW_MODELS=2
        SHADOW_EPOCHS=1
        SHADOW_BS=8
        EPOCHS_MAIN=1
        EPOCHS_BRANCH=1
        KFOLD_FOLDS=2
        KFOLD_EPOCHS=1
        TRAIN_BLOCKS_LAST6=2
        TRAIN_BLOCKS_LAST5=2
        TRAIN_BLOCKS_ALL=4
        ORACLE_WEIGHT_SAMPLES=1
        ;;
    *)
        echo "ERROR: Unknown MODE='$MODE' (expected full, fast, or smoke)" >&2
        exit 1
        ;;
esac

mkdir -p "$OUT_DIR"

echo "=================================================================="
echo " Task 3 Hybrid v2 Unlearning Pipeline"
echo "------------------------------------------------------------------"
echo " REPO_DIR     : $REPO_UNLEARNING_DIR"
echo " TASK_DIR     : $TASK_DIR"
echo " OUT_DIR      : $OUT_DIR"
echo " MODE         : $MODE (STAGES=$STAGES, USE_INDOMAIN=$USE_INDOMAIN, SKIP_SHADOW=$SKIP_SHADOW, FORCE=$FORCE)"
echo " DEVICE/AMP   : $DEVICE (${NGPUS}x GPU) / $AMP"
echo " PYTHON       : $PY"
echo "=================================================================="

# ---------------------------------------------------------------------------
# 4. Helpers
# ---------------------------------------------------------------------------
needs_run() {
    local artifact="$1"
    [[ "$FORCE" == "1" || ! -f "$artifact" ]]
}

run_ul() {
    local script_name="$1"
    shift
    PYTHONPATH="$REPO_UNLEARNING_DIR:$TASK_DIR:${PYTHONPATH:-}" \
        "$PY" -u "$REPO_UNLEARNING_DIR/$script_name" "$@"
}

ensure_indomain_deps() {
    local missing
    missing="$("$PY" - <<'PY'
import importlib
bad = []
for mod, pkg in [("diffusers", "diffusers"), ("transformers", "transformers"), ("accelerate", "accelerate")]:
    try:
        importlib.import_module(mod)
    except Exception:
        bad.append(pkg)
print(" ".join(bad))
PY
)"
    if [[ -n "$missing" ]]; then
        if [[ "$AUTO_INSTALL_DEPS" == "1" ]]; then
            echo "[indomain] Installing missing packages: $missing"
            "$PY" -m pip install -q $missing
        else
            echo "ERROR: Missing packages for gen_indomain.py: $missing" >&2
            echo "Install with: $PY -m pip install $missing (or set AUTO_INSTALL_DEPS=1 / USE_INDOMAIN=0)" >&2
            exit 1
        fi
    fi
}

ensure_pool_path() {
    if [[ -n "${POOL_PATH:-}" ]]; then
        if [[ ! -e "$POOL_PATH" ]]; then
            echo "ERROR: Specified POOL_PATH does not exist: $POOL_PATH" >&2
            exit 1
        fi
        return 0
    fi

    if [[ -f "$TASK_DIR/coco224.npy" ]]; then
        POOL_PATH="$TASK_DIR/coco224.npy"
        return 0
    fi

    local cand_dir
    for cand_dir in \
        "$OUT_DIR/pools/val2017" \
        "$TASK_DIR/output/hybrid_v2/pools/val2017" \
        "$TASK_DIR/output/hybrid/pools/val2017"; do
        if [[ -d "$cand_dir" ]] && find "$cand_dir" -maxdepth 1 -name '*.jpg' -print -quit | grep -q .; then
            POOL_PATH="$cand_dir"
            return 0
        fi
    done

    if [[ "$AUTO_DOWNLOAD_COCO" != "1" ]]; then
        echo "ERROR: No POOL_PATH set and $TASK_DIR/coco224.npy not found (AUTO_DOWNLOAD_COCO=0)." >&2
        exit 1
    fi

    local coco_dir="$OUT_DIR/pools/val2017"
    echo "[retain] Downloading COCO val2017 (~778 MB) into $OUT_DIR/pools ..."
    mkdir -p "$OUT_DIR/pools"
    local zip_path="$OUT_DIR/pools/val2017.zip"
    if [[ ! -f "$zip_path" ]]; then
        if command -v curl >/dev/null 2>&1; then
            curl -fL --progress-bar -o "$zip_path.tmp" "http://images.cocodataset.org/zips/val2017.zip"
            mv "$zip_path.tmp" "$zip_path"
        elif command -v wget >/dev/null 2>&1; then
            wget -q --show-progress -O "$zip_path.tmp" "http://images.cocodataset.org/zips/val2017.zip"
            mv "$zip_path.tmp" "$zip_path"
        else
            "$PY" - "$zip_path" <<'PY'
import sys, urllib.request
urllib.request.urlretrieve("http://images.cocodataset.org/zips/val2017.zip", sys.argv[1])
PY
        fi
    fi

    echo "[retain] Extracting COCO val2017 ..."
    "$PY" - "$zip_path" "$OUT_DIR/pools" <<'PY'
import sys, zipfile
with zipfile.ZipFile(sys.argv[1], "r") as zf:
    zf.extractall(sys.argv[2])
PY
    rm -f "$zip_path"
    POOL_PATH="$coco_dir"
}

# ---------------------------------------------------------------------------
# Stage 0: Forensic Diagnostics
# ---------------------------------------------------------------------------
if stage_enabled diagnose; then
    mkdir -p "$OUT_DIR/diagnose"
    if needs_run "$OUT_DIR/diagnose/diagnostics.json"; then
        echo ""
        echo ">>> [Stage 0/6] Forensic Diagnostics (diagnose.py)"
        run_ul diagnose.py \
            --task-dir "$TASK_DIR" \
            --out-dir "$OUT_DIR/diagnose" \
            --save-grids "$DIAG_GRIDS" \
            --device "$DEVICE" \
            --amp "$AMP"
    else
        echo ">>> [Stage 0/6] diagnose already exists (set FORCE=1 to rerun)"
    fi
fi

# ---------------------------------------------------------------------------
# Stage 0.5: In-Domain 45-Class Retain Generation (SDXL-Turbo, Multi-GPU Sharded)
# ---------------------------------------------------------------------------
INDOMAIN_FILE="${INDOMAIN_FILE:-$OUT_DIR/pools/gen_indomain.npy}"
if [[ ! -f "$INDOMAIN_FILE" ]]; then
    for cand_in in "$TASK_DIR/gen_indomain.npy" "$TASK_DIR/output/hybrid/pools/gen_indomain.npy"; do
        if [[ -f "$cand_in" ]]; then
            INDOMAIN_FILE="$cand_in"
            break
        fi
    done
fi

if stage_enabled indomain && [[ "$USE_INDOMAIN" == "1" ]] && [[ "$INDOMAIN_PER_CLASS" -gt 0 ]]; then
    mkdir -p "$(dirname "$INDOMAIN_FILE")"
    if needs_run "$INDOMAIN_FILE"; then
        if [[ -f "$TASK_DIR/gen0.npy" && -f "$TASK_DIR/gen1.npy" && "$FORCE" != "1" ]]; then
            echo ""
            echo ">>> [Stage 0.5/6] Found existing T3-011 shards ($TASK_DIR/gen0.npy + gen1.npy); merging into $INDOMAIN_FILE"
            "$PY" - "$TASK_DIR/gen0.npy" "$TASK_DIR/gen1.npy" "$INDOMAIN_FILE" <<'PY'
import sys, numpy as np
from pathlib import Path
g0, g1, out_p = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
arr = np.concatenate([np.load(g0), np.load(g1)], axis=0)
np.save(out_p, arr)
l0, l1 = g0.with_suffix(".labels.npy"), g1.with_suffix(".labels.npy")
if l0.is_file() and l1.is_file():
    np.save(out_p.with_suffix(".labels.npy"), np.concatenate([np.load(l0), np.load(l1)], axis=0))
print("Merged shards ->", out_p, arr.shape)
PY
        elif [[ "$NGPUS" -gt 1 ]]; then
            echo ""
            echo ">>> [Stage 0.5/6] Generate In-Domain 45-Class Anchors across ${NGPUS} GPUs (per_class=$INDOMAIN_PER_CLASS)"
            ensure_indomain_deps
            SHARD_DIR="$(dirname "$INDOMAIN_FILE")/shards"
            mkdir -p "$SHARD_DIR"
            PIDS=()
            for ((s=0; s<NGPUS; s++)); do
                CUDA_VISIBLE_DEVICES="$s" PYTHONPATH="$REPO_UNLEARNING_DIR:$TASK_DIR:${PYTHONPATH:-}" \
                    "$PY" -u "$REPO_UNLEARNING_DIR/gen_indomain.py" \
                    --out "$SHARD_DIR/shard_${s}.npy" \
                    --per-class "$INDOMAIN_PER_CLASS" \
                    --shard "$s" \
                    --nshards "$NGPUS" \
                    --batch "${INDOMAIN_BATCH:-16}" > "$SHARD_DIR/shard_${s}.log" 2>&1 &
                PIDS+=("$!")
            done
            FAIL=0
            for pid in "${PIDS[@]}"; do
                wait "$pid" || FAIL=1
            done
            if [[ "$FAIL" -ne 0 ]]; then
                cat "$SHARD_DIR"/shard_*.log >&2 || true
                echo "ERROR: Multi-GPU gen_indomain.py failed." >&2
                exit 1
            fi
            "$PY" - "$SHARD_DIR" "$NGPUS" "$INDOMAIN_FILE" <<'PY'
import sys, numpy as np
from pathlib import Path
sdir, n, out_p = Path(sys.argv[1]), int(sys.argv[2]), Path(sys.argv[3])
imgs = [np.load(sdir / f"shard_{s}.npy") for s in range(n)]
lbls = [np.load(sdir / f"shard_{s}.labels.npy") for s in range(n)]
arr = np.concatenate(imgs, axis=0)
np.save(out_p, arr)
np.save(out_p.with_suffix(".labels.npy"), np.concatenate(lbls, axis=0))
print(f"Merged {n} shards -> {out_p} {arr.shape}")
PY
        else
            echo ""
            echo ">>> [Stage 0.5/6] Generate In-Domain 45-Class Retain Anchors (gen_indomain.py, per_class=$INDOMAIN_PER_CLASS)"
            ensure_indomain_deps
            run_ul gen_indomain.py \
                --out "$INDOMAIN_FILE" \
                --per-class "$INDOMAIN_PER_CLASS" \
                --batch "${INDOMAIN_BATCH:-16}"
        fi
    else
        echo ">>> [Stage 0.5/6] in-domain anchors already exist at $INDOMAIN_FILE (set FORCE=1 to rerun)"
    fi
elif [[ "$USE_INDOMAIN" != "1" ]]; then
    echo ">>> [Stage 0.5/6] Skipping in-domain generation (USE_INDOMAIN=$USE_INDOMAIN)"
fi

# ---------------------------------------------------------------------------
# Stage 1: Deduplicated Class-Balanced Retain Proxy (In-Domain + COCO)
# ---------------------------------------------------------------------------
RETAIN_FIT="$OUT_DIR/retain/retain_fit.npy"
RETAIN_AUDIT_FILE="$OUT_DIR/retain/retain_audit.npy"
RETAIN_AUDIT_ACTIVE="$OUT_DIR/retain/retain_audit_active.npy"
RETAIN_AUDIT_INACTIVE="$OUT_DIR/retain/retain_audit_inactive.npy"

if stage_enabled retain; then
    mkdir -p "$OUT_DIR/retain"
    if needs_run "$RETAIN_FIT"; then
        echo ""
        echo ">>> [Stage 1/6] Build Retain Proxy (build_retain_proxy.py)"
        ensure_pool_path
        POOL_ARGS=("$POOL_PATH")
        if [[ -f "$INDOMAIN_FILE" ]]; then
            POOL_ARGS=("$INDOMAIN_FILE" "$POOL_PATH")
        fi
        echo "[retain] Using pools: ${POOL_ARGS[*]}"
        run_ul build_retain_proxy.py \
            --task-dir "$TASK_DIR" \
