            --retain "$RETAIN_FIT" \
            --out "$SHADOW_GOLD" \
            --num-models "$SHADOW_MODELS" \
            --epochs "$SHADOW_EPOCHS" \
            --bs "$SHADOW_BS" \
            --lr "${SHADOW_LR:-1e-4}" \
            --device "$DEVICE" \
            --amp "$AMP"
    else
        echo ">>> [Stage 2/6] shadow_gold.pt already exists (set FORCE=1 to rerun)"
    fi
elif [[ "$SKIP_SHADOW" == "1" ]]; then
    echo ">>> [Stage 2/6] Skipping Shadow-Gold training (SKIP_SHADOW=1)"
