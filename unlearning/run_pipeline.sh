# ---------------------------------------------------------------------------
# Stage 3: Memorization Scoring & Heavy-Tail Margin+Patch Oracle
# ---------------------------------------------------------------------------
ORACLE_FILE="$OUT_DIR/oracle/oracle_targets.pt"

if stage_enabled oracle; then
    mkdir -p "$OUT_DIR/oracle"
    if needs_run "$ORACLE_FILE"; then
        echo ""
        echo ">>> [Stage 3/6] Build Heavy-Tail Margin+Patch Oracle (build_oracle.py)"
        ORACLE_EXTRA=()
        [[ "$SKIP_SHADOW" != "1" && -f "$SHADOW_GOLD" ]] && ORACLE_EXTRA+=(--shadow-gold "$SHADOW_GOLD")
        [[ -n "${EXT_EMBEDDINGS:-}" && -f "${EXT_EMBEDDINGS}" ]] && ORACLE_EXTRA+=(--ext-embeddings "$EXT_EMBEDDINGS")
        run_ul build_oracle.py \
            --task-dir "$TASK_DIR" \
            --out "$ORACLE_FILE" \
            --delta-mode margin_power \
            --base-delta 12.0 \
            --margin-power -2.2 \
            --fragility-boost 0.25 \
            --soften 0.0 \
            --w-shift 1.0 \
            --w-oof 0.0 \
            --w-corrupt 0.0 \
            --num-weight-samples "$ORACLE_WEIGHT_SAMPLES" \
            "${ORACLE_EXTRA[@]}" \
            --device "$DEVICE" \
            --amp "$AMP"
    else
        echo ">>> [Stage 3/6] oracle_targets.pt already exists (set FORCE=1 to rerun)"
    fi
fi

# Shared optional arguments for training waves
SHARED_OPT=()
